"""Transcribe every operation's x-foresignal-permission in docs/OpenAPI.json into AccessPermissions.java (R2-004).

Every operation gets a row, with a null permission where it carries none: a row for an operation without one keeps a
broader template from answering for it (GET /v1/precursors/batches is not GET /v1/precursors/{id}).

The permission table is the second half of AccessPolicy: the scope rules are written by hand in contract order, the
permission rules are transcribed from the contract by this script, so the two cannot drift silently;
AccessPolicySyncTest checks both against the spec for every operation. Run it after any change to an
x-foresignal-permission:

    python3 scripts/generate-access-permissions.py docs/OpenAPI.json src/main/java/ai/foresignal/security/AccessPermissions.java

Python 3 standard library only.
"""
import json
import re
import sys

spec_path, out_path = sys.argv[1], sys.argv[2]
spec = json.loads(open(spec_path, encoding="utf-8").read())
rows = []
for path, item in spec["paths"].items():
    for method, op in item.items():
        if not isinstance(op, dict) or "operationId" not in op:
            continue
        pattern = re.sub(r"\{[^/}]+\}", "*", path)
        rows.append((method.upper(), pattern, op.get("x-foresignal-permission"), op["operationId"]))


def specificity(row):
    # Fewer wildcards first, then longer literal text, so a literal segment wins over a template at the same depth.
    pattern = row[1]
    return (pattern.count("*"), -len(pattern.replace("*", "")), pattern, row[0])


rows.sort(key=specificity)
lines = []
for method, pattern, permission, operation_id in rows:
    value = "null" if permission is None else f'"{permission}"'
    lines.append(f'            rule("{method}", "{pattern}", {value}), // {operation_id}')
body = "\n".join(lines)
java = f'''package ai.foresignal.security;

import java.util.List;

/**
 * The per-operation permission table (prompt R2-004): every {{@code x-foresignal-permission}} in
 * {{@code docs/OpenAPI.json}}, as (method, Ant pattern, permission key). Generated by
 * {{@code scripts/generate-access-permissions.py}} from the contract; regenerate it rather than editing it by hand.
 * {{@code AccessPolicySyncTest}} checks it against the spec for every operation.
 *
 * <p>Every operation has a row; a null permission means the operation carries none (a session is then gated on its
 * scope). Listing those too keeps a broader template from answering for an operation it does not describe.
 *
 * <p>Ordered specific first (fewer wildcards, then longer literal text), and the first match wins, so a literal
 * segment beats a path template at the same depth.
 */
final class AccessPermissions {{

    private AccessPermissions() {{}}

    /**
     * One row: an operation's method, its path as an Ant pattern ({{@code {{param}}}} becomes {{@code *}}) and the
     * permission a session must hold.
     *
     * @param method the HTTP method, upper case
     * @param pattern the Ant pattern
     * @param permission the permission key, or null when the operation carries none
     */
    record PermissionRule(String method, String pattern, String permission) {{}}

    private static PermissionRule rule(String method, String pattern, String permission) {{
        return new PermissionRule(method, pattern, permission);
    }}

    /** Every row, specific first. */
    static final List<PermissionRule> RULES = List.of(
{body.rstrip(",").rstrip()}
    );
}}
'''
# The last row must not end with a comma.
java = re.sub(r",( // [A-Za-z0-9]+)\n    \);", r"\1\n    );", java)
open(out_path, "w", encoding="utf-8").write(java)
print(f"{len(rows)} rows ({sum(1 for r in rows if r[2])} with a permission) written to {out_path}")
