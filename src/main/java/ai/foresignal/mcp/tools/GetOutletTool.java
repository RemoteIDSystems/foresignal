package ai.foresignal.mcp.tools;

import static ai.foresignal.mcp.JsonSchemas.object;
import static ai.foresignal.mcp.JsonSchemas.props;

import ai.foresignal.api.error.NotFoundException;
import ai.foresignal.mcp.ForesignalMcpTool;
import ai.foresignal.mcp.JsonSchemas;
import ai.foresignal.mcp.ToolContext;
import ai.foresignal.mcp.ToolResult;
import ai.foresignal.media.outlet.OutletRegistry;
import ai.foresignal.news.NewsViews;
import ai.foresignal.security.EgressPath;
import ai.foresignal.security.Scope;
import ai.foresignal.security.restrict.RestrictedRead;
import java.util.Map;
import org.springframework.stereotype.Component;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * {@code get_outlet} (read; prompt 133): one news outlet by id or domain, with its ratings per provider (license and
 * date), the consensus per dimension with its provider breakdown, type, country and owner. Ratings are imported from
 * declared providers, never generated.
 */
@Component
@RestrictedRead("outlets are registry entries, not records")
public class GetOutletTool implements ForesignalMcpTool {

    static final Map<String, Object> INPUT = object(props(
            "outletId", JsonSchemas.string("The outlet id"),
            "domain", JsonSchemas.string("Or a domain the outlet publishes on, for example reuters.com")));

    private final NewsViews views;
    private final OutletRegistry outlets;
    private final JsonMapper json;

    /** Creates the tool. */
    public GetOutletTool(NewsViews views, OutletRegistry outlets, JsonMapper json) {
        this.views = views;
        this.outlets = outlets;
        this.json = json;
    }

    @Override
    public String name() {
        return "get_outlet";
    }

    @Override
    public String title() {
        return "Get a news outlet";
    }

    @Override
    public String description() {
        return "Returns a news outlet (by outletId or domain): type, country, owner organization, Wikidata item, its"
                + " ratings per provider (lean -2..+2, factuality 1..5, state affiliation, ownership type) with each"
                + " provider's license and date, and the consensus per dimension with the provider breakdown and"
                + " disagreement. Ratings come only from declared providers; none is generated by a model.";
    }

    @Override
    public Map<String, Object> inputSchema() {
        return INPUT;
    }

    @Override
    public Map<String, Object> outputSchema() {
        return JsonSchemas.objectOutput("MediaOutlet");
    }

    @Override
    public Scope requiredScope() {
        return Scope.READ;
    }

    @Override
    public boolean readOnlyHint() {
        return true;
    }

    @Override
    public boolean idempotentHint() {
        return true;
    }

    @Override
    public ToolResult call(ToolContext context, JsonNode args) {
        String id = ListNewsStoriesTool.text(args, "outletId");
        String domain = ListNewsStoriesTool.text(args, "domain");
        if (id == null && domain != null) {
            id = outlets.byDomain(domain).map(OutletRegistry.Outlet::id).orElse(null);
            if (id == null) {
                return ToolResult.error("No outlet publishes on '" + domain + "'.");
            }
        }
        if (id == null) {
            return ToolResult.error("outletId or domain is required");
        }
        try {
            return ToolResult.json(json.valueToTree(views.outlet(id, EgressPath.MCP)));
        } catch (NotFoundException e) {
            return ToolResult.error(e.getMessage());
        }
    }
}
