package ai.foresignal.reference.ukr;

import ai.foresignal.source.formats.geojson.GeoJsonReader;
import ai.foresignal.source.spi.Geo;
import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.util.HashMap;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;
import org.locationtech.jts.geom.Geometry;
import org.locationtech.jts.geom.util.GeometryFixer;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * Oblast and raion polygons for the Ukrainian alert sources (prompt 081).
 *
 * <p><strong>Data</strong> (bundled under {@value #RESOURCE_DIR}, generated by {@code scripts/build-ukr-regions.py};
 * attribution in the {@code NOTICE} there and in {@code THIRD_PARTY_NOTICES.md}):
 * <ul>
 *   <li>{@code adm1.geojson}: the 27 first-level units of geoBoundaries gbHumanitarian UKR (24 oblasts, Crimea, Kyiv
 *       city, Sevastopol), CC BY 3.0 IGO, simplified to at most 1,500 vertices per polygon;
 *   <li>{@code adm2.geojson}: the 139 second-level units (the 2020 raions, Kyiv, Sevastopol and the Chornobyl zone);
 *   <li>{@code alerts-in-ua-uids.json}: alerts.in.ua {@code location_uid} to a boundary id;
 *   <li>{@code siren-region-ids.json}: siren.pp.ua {@code regionId} to a boundary id.
 * </ul>
 *
 * <p><strong>Lookup:</strong> a crosswalk entry has a {@code boundary} (oblasts, cities with special status,
 * raions: the polygon is the region itself) or a {@code parent} (hromadas and communities: the polygon of the raion
 * that contains them, so the region is {@linkplain Region#approximate() approximate}). An id in neither table, or one
 * with neither field, yields no region and is logged once per id and table.
 *
 * <p>The files are read on the first lookup, not at startup, so an instance that never enables a Ukrainian source
 * never loads them. A polygon that simplification left invalid (a ring touching itself) is repaired with JTS's
 * {@link GeometryFixer} on load.
 */
@Component
public class UaRegionIndex {

    /** The classpath folder of the bundled files. */
    public static final String RESOURCE_DIR = "/geo/ukr/";

    /** The crosswalk of alerts.in.ua location UIDs. */
    public static final String ALERTS_IN_UA_TABLE = "alerts-in-ua-uids.json";

    /** The crosswalk of siren.pp.ua region ids. */
    public static final String SIREN_TABLE = "siren-region-ids.json";

    /** The boundary files. */
    static final String[] BOUNDARY_FILES = {"adm1.geojson", "adm2.geojson"};

    private static final Logger log = LoggerFactory.getLogger(UaRegionIndex.class);
    private static final JsonMapper JSON = JsonMapper.builder().build();
    private static final GeoJsonReader READER = new GeoJsonReader(20_000, GeoJsonReader.DEFAULT_MAX_COLLECTION_DEPTH);

    /**
     * One resolved region.
     *
     * @param id the upstream id that was looked up
     * @param name the region's name in the crosswalk (Ukrainian)
     * @param type the crosswalk type ({@code oblast}, {@code city}, {@code raion}, {@code hromada} for alerts.in.ua;
     *     {@code State}, {@code District}, {@code Community} for siren.pp.ua)
     * @param boundaryId the id of the boundary whose polygon is returned
     * @param geometry the polygon, SRID 4326
     * @param approximate true when the polygon is a containing raion rather than the region itself
     */
    public record Region(String id, String name, String type, String boundaryId, Geometry geometry,
            boolean approximate) {}

    /** One crosswalk entry. */
    record Entry(String name, String type, String boundary, String parent) {}

    /** The loaded data. */
    record Data(Map<String, Geometry> boundaries, Map<String, Entry> alerts, Map<String, Entry> siren) {}

    private volatile Data data;
    private final Set<String> logged = ConcurrentHashMap.newKeySet();

    /** Creates the index; nothing is read until the first lookup. */
    public UaRegionIndex() {}

    /**
     * The region of an alerts.in.ua {@code location_uid}.
     *
     * @return the region, or empty when the UID is blank, unknown or unmatched (logged once)
     */
    public Optional<Region> byAlertsUid(String uid) {
        return resolve(ALERTS_IN_UA_TABLE, data().alerts(), uid);
    }

    /**
     * The region of a siren.pp.ua {@code regionId}.
     *
     * @return the region, or empty when the id is blank, unknown or unmatched (logged once)
     */
    public Optional<Region> bySirenRegionId(String regionId) {
        return resolve(SIREN_TABLE, data().siren(), regionId);
    }

    /** The polygon of a boundary id ({@code adm1:…} or {@code adm2:…}), or empty when unknown. */
    public Optional<Geometry> boundary(String boundaryId) {
        return Optional.ofNullable(boundaryId == null ? null : data().boundaries().get(boundaryId));
    }

    /** How many boundaries are loaded. */
    public int boundaryCount() {
        return data().boundaries().size();
    }

    /** The crosswalk name and type of an alerts.in.ua UID, or empty when unknown (no logging). */
    public Optional<String> alertsName(String uid) {
        return Optional.ofNullable(uid == null ? null : data().alerts().get(uid.strip())).map(Entry::name);
    }

    /** The crosswalk name of a siren.pp.ua region id, or empty when unknown (no logging). */
    public Optional<String> sirenName(String regionId) {
        return Optional.ofNullable(regionId == null ? null : data().siren().get(regionId.strip())).map(Entry::name);
    }

    private Optional<Region> resolve(String table, Map<String, Entry> crosswalk, String rawId) {
        if (rawId == null || rawId.isBlank()) {
            return Optional.empty();
        }
        String id = rawId.strip();
        Entry entry = crosswalk.get(id);
        if (entry != null) {
            Map<String, Geometry> boundaries = data().boundaries();
            if (entry.boundary() != null && boundaries.containsKey(entry.boundary())) {
                return Optional.of(new Region(id, entry.name(), entry.type(), entry.boundary(),
                        boundaries.get(entry.boundary()), false));
            }
            if (entry.parent() != null && boundaries.containsKey(entry.parent())) {
                return Optional.of(new Region(id, entry.name(), entry.type(), entry.parent(),
                        boundaries.get(entry.parent()), true));
            }
        }
        if (logged.add(table + ":" + id)) {
            log.info("Ukraine regions: {} id {} {}; its alerts are stored without geometry", table, id,
                    entry == null ? "is not in the crosswalk" : "(" + entry.name() + ") has no boundary");
        }
        return Optional.empty();
    }

    private Data data() {
        Data loaded = data;
        if (loaded == null) {
            synchronized (this) {
                loaded = data;
                if (loaded == null) {
                    loaded = load();
                    data = loaded;
                }
            }
        }
        return loaded;
    }

    private static Data load() {
        Map<String, Geometry> boundaries = new HashMap<>();
        for (String file : BOUNDARY_FILES) {
            JsonNode features = read(file).path("features");
            for (JsonNode feature : features) {
                String id = feature.path("properties").path("id").asString(null);
                if (id == null || id.isBlank()) {
                    continue;
                }
                Geometry geometry = READER.read(feature.get("geometry"));
                if (!geometry.isValid()) {
                    // Simplifying and rounding can leave a ring touching itself; spatial predicates need valid input.
                    geometry = GeometryFixer.fix(geometry);
                }
                geometry.setSRID(Geo.SRID);
                boundaries.put(id, geometry);
            }
        }
        return new Data(Map.copyOf(boundaries), crosswalk(ALERTS_IN_UA_TABLE), crosswalk(SIREN_TABLE));
    }

    private static Map<String, Entry> crosswalk(String file) {
        Map<String, Entry> out = new HashMap<>();
        JsonNode regions = read(file).path("regions");
        for (Map.Entry<String, JsonNode> region : regions.properties()) {
            JsonNode node = region.getValue();
            out.put(region.getKey(), new Entry(node.path("name").asString(null), node.path("type").asString(null),
                    node.path("boundary").asString(null), node.path("parent").asString(null)));
        }
        return Map.copyOf(out);
    }

    private static JsonNode read(String file) {
        try (InputStream in = UaRegionIndex.class.getResourceAsStream(RESOURCE_DIR + file)) {
            if (in == null) {
                throw new IllegalStateException("The bundled Ukraine region file " + RESOURCE_DIR + file
                        + " is missing");
            }
            return JSON.readTree(in);
        } catch (IOException e) {
            throw new UncheckedIOException("Could not read " + RESOURCE_DIR + file, e);
        }
    }
}
