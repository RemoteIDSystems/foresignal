package ai.foresignal.reference;

import ai.foresignal.source.formats.geojson.GeoJsonReader;
import java.io.IOException;
import java.io.InputStream;
import java.util.List;
import java.util.zip.GZIPInputStream;
import org.locationtech.jts.geom.Coordinate;
import org.locationtech.jts.geom.Envelope;
import org.locationtech.jts.geom.Geometry;
import org.locationtech.jts.geom.GeometryFactory;
import org.locationtech.jts.geom.Point;
import org.locationtech.jts.geom.PrecisionModel;
import org.locationtech.jts.geom.prep.PreparedGeometry;
import org.locationtech.jts.geom.prep.PreparedGeometryFactory;
import org.locationtech.jts.geom.util.GeometryFixer;
import org.locationtech.jts.index.strtree.STRtree;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * Simplified country polygons bundled with the application ({@code reference/countries-simple.geojson.gz},
 * prompt 040), so {@link RegionTagger} can still give a country when no reference data is loaded.
 *
 * <p>Generated by {@code scripts/build-countries.py} from Natural Earth 50m admin-0 (10m for the few
 * countries 50m lacks), coordinates rounded to 0.01°. Accurate to about a kilometre away from coasts
 * and borders; points that fall in no polygon have no country. Loaded lazily on first use.
 */
@Component
public class BundledCountryPolygons {

    /** The bundled polygons. */
    public static final String RESOURCE = "/reference/countries-simple.geojson.gz";

    private static final Logger log = LoggerFactory.getLogger(BundledCountryPolygons.class);
    private static final GeometryFactory WGS84 = new GeometryFactory(new PrecisionModel(), 4326);
    private static final JsonMapper JSON = JsonMapper.builder().build();

    private record Entry(String iso2, PreparedGeometry geometry) {}

    private volatile STRtree index;

    /** The ISO2 code of the country containing {@code (lon, lat)}, or null. */
    public String iso2At(double lon, double lat) {
        STRtree tree = index();
        if (tree == null) {
            return null;
        }
        Point point = WGS84.createPoint(new Coordinate(lon, lat));
        @SuppressWarnings("unchecked")
        List<Entry> candidates = tree.query(new Envelope(lon, lon, lat, lat));
        for (Entry entry : candidates) {
            if (entry.geometry().covers(point)) {
                return entry.iso2();
            }
        }
        return null;
    }

    /** The number of countries loaded (0 when the resource is missing or unreadable). */
    public int size() {
        STRtree tree = index();
        return tree == null ? 0 : tree.size();
    }

    private STRtree index() {
        STRtree current = index;
        if (current == null) {
            synchronized (this) {
                current = index;
                if (current == null) {
                    current = load();
                    index = current;
                }
            }
        }
        return current.size() == 0 ? null : current;
    }

    private static STRtree load() {
        STRtree tree = new STRtree();
        try (InputStream raw = BundledCountryPolygons.class.getResourceAsStream(RESOURCE)) {
            if (raw == null) {
                log.warn("The bundled country polygons {} are missing; offline country tagging is off", RESOURCE);
                tree.build();
                return tree;
            }
            try (InputStream in = new GZIPInputStream(raw)) {
                JsonNode root = JSON.readTree(in);
                GeoJsonReader reader = new GeoJsonReader(5_000_000, 4);
                for (JsonNode feature : root.path("features")) {
                    String iso2 = feature.path("properties").path("iso2").asString(null);
                    if (iso2 == null || feature.path("geometry").isMissingNode()) {
                        continue;
                    }
                    Geometry geometry = GeometryFixer.fix(reader.read(feature.get("geometry")));
                    tree.insert(geometry.getEnvelopeInternal(),
                            new Entry(iso2, PreparedGeometryFactory.prepare(geometry)));
                }
            }
        } catch (IOException | RuntimeException e) {
            log.warn("Could not read the bundled country polygons: {}", e.getMessage());
            tree = new STRtree();
        }
        tree.build();
        return tree;
    }
}
