#!/usr/bin/env node
/**
 * Embeds the exported EDP JSON Schemas into src/generated/schemas.ts.
 *
 * The schemas are generated from docs/OpenAPI.json into docs/protocol/edp-1.0/ by
 * scripts/export-edp-schemas.py; this library embeds them as a TypeScript module so it works in any
 * runtime and bundler without JSON imports. Run `npm run sync-schemas` after the schemas change;
 * test/schemas-sync.test.ts fails while the embedded copies differ.
 *
 * Usage: node scripts/sync-schemas.mjs [SOURCE_DIR]
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(process.argv[2] ?? join(here, "..", "..", "..", "docs", "protocol", "edp-1.0"));
const target = join(here, "..", "src", "generated", "schemas.ts");
const files = readdirSync(source).filter((f) => f.endsWith(".schema.json")).sort();
if (files.length === 0) {
  console.error(`No *.schema.json files in ${source}`);
  process.exit(1);
}
const entries = files.map((file) => {
  const name = file.replace(/\.schema\.json$/, "");
  const schema = JSON.parse(readFileSync(join(source, file), "utf8"));
  return `  ${JSON.stringify(name)}: ${JSON.stringify(schema, null, 2).replace(/\n/g, "\n  ")},`;
});
const banner = [
  "// Generated by scripts/sync-schemas.mjs from docs/protocol/edp-1.0/*.schema.json. Do not edit by hand.",
  "",
  "/** The exported EDP 1.0 JSON Schemas, by name. */",
  "export const EXPORTED_SCHEMAS: Record<string, Record<string, unknown>> = {",
];
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `${banner.join("\n")}\n${entries.join("\n")}\n};\n`);
console.log(`wrote ${files.length} schemas to ${target}`);
